export type Lang = 'pt' | 'en' | 'es';
export type LanguagePref = 'auto' | Lang;

export function getDeviceLocale(): string {
	if (typeof navigator === 'undefined') return 'en-US';
	return navigator.language || (navigator as unknown as { userLanguage?: string }).userLanguage || 'en-US';
}

export function detectLanguage(): Lang {
	const l = getDeviceLocale().toLowerCase();
	if (l.startsWith('pt')) return 'pt';
	if (l.startsWith('es')) return 'es';
	return 'en';
}

export function resolveLanguage(pref?: string): Lang {
	if (pref === 'pt' || pref === 'en' || pref === 'es') return pref;
	return detectLanguage();
}

export function resolveMinecraftLocale(pref?: string): string {
	if (pref === 'pt') return 'pt-BR';
	if (pref === 'en') return 'en-US';
	if (pref === 'es') return 'es-ES';
	return getDeviceLocale();
}

